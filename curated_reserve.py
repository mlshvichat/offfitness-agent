def digest(post):
    return hashlib.sha256(post.encode("utf-8")).hexdigest()

def valid(candidate):
    for channel, entries in TEXTS.items():
        for ident, hour, topic, post in entries:
            if (candidate.get("template_id") == channel + ":" + ident
                and candidate.get("topic") == topic and candidate.get("post") == post
                and candidate.get("sha256") == digest(post)
                and candidate.get("approval", {}).get("source") == "builtin-editorial-v1"):
                return True
    return False

def candidates(agent, channel, history, ready, hour):
    result = []
    for ident, slot, topic, post in sorted(TEXTS[channel], key=lambda x: x[1] != hour):
        try:
            agent.validate(topic, post, history + ready + result)
            if agent.editorial.local_findings(post, history + ready + result):
                continue
        except ValueError:
            continue
        result.append({"template_id": channel + ":" + ident, "slot": slot,
            "topic": topic, "post": post, "sha256": digest(post),
            "approval": {"source": "builtin-editorial-v1", "status": "approved",
                "reviewer": "Codex offline editorial review 2026-11-03",
                "checks": ["evergreen content", "no invented facts or offers",
                           "Russian style", "history and exact text verification"]}})
    return result
